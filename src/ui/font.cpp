Font Font::create_debug() {
    Font font;
    font.em_size_ = 8.0f;
    font.ascender_ = 7.0f / 8.0f;    // baseline between rows 6 and 7
    font.descender_ = -1.0f / 8.0f;
    font.line_height_ = 1.25f;
    font.atlas_width_ = kColumns * kCell;    // 128
    font.atlas_height_ = kRows * kCell;      // 48
    font.atlas_.assign(font.atlas_width_ * font.atlas_height_, 0);

    const float atlas_w = static_cast<float>(font.atlas_width_);
    const float atlas_h = static_cast<float>(font.atlas_height_);

    font.glyphs_.reserve(95);
    for (uint32_t i = 0; i < 95; ++i) {
        const uint32_t col = i % kColumns;
        const uint32_t row = i / kColumns;
        const uint32_t px = col * kCell;
        const uint32_t py = row * kCell;
        bool any = false;
        for (uint32_t y = 0; y < kCell; ++y) {
            const uint8_t bits = kDebugFont[i][y];
            if (bits) any = true;
            for (uint32_t x = 0; x < kCell; ++x) {
                if (bits & (0x80u >> x))
                    font.atlas_[(py + y) * font.atlas_width_ + px + x] = 0xFF;
            }
        }
        Glyph g;
        g.codepoint = 32 + i;
        g.advance = 1.0f;   // monospace, one em per cell
        g.plane_l = 0.0f;
        g.plane_r = 1.0f;
        g.plane_t = 7.0f / 8.0f;
        g.plane_b = -1.0f / 8.0f;
        g.uv_l = static_cast<float>(px) / atlas_w;
        g.uv_t = static_cast<float>(py) / atlas_h;
        g.uv_r = static_cast<float>(px + kCell) / atlas_w;
        g.uv_b = static_cast<float>(py + kCell) / atlas_h;
        g.has_geometry = any;
        font.glyphs_.push_back(g);
    }
    return font;
}

std::optional<Font> Font::load_msdf(const std::filesystem::path& atlas_png,
                                    const std::filesystem::path& metrics_json) {
    auto png = read_file_bytes(atlas_png);
    auto met = read_file_bytes(metrics_json);
    if (!png || !met) return std::nullopt;

    ImageRgba image;
    if (!decode_png(png->data(), png->size(), &image) || image.width == 0)
        return std::nullopt;

    const json::ParseResult parsed = json::parse(std::string_view(
        reinterpret_cast<const char*>(met->data()), met->size()));
    if (!parsed.value) return std::nullopt;
    const json::Value& root = *parsed.value;
    const json::Value& atlas = root.get("atlas");
    const json::Value& metrics = root.get("metrics");
    const json::Value& glyphs = root.get("glyphs");
    if (!atlas.is_object() || !metrics.is_object() || !glyphs.is_array())
        return std::nullopt;

    Font font;
    font.msdf_ = true;
    font.atlas_width_ = image.width;
    font.atlas_height_ = image.height;
    font.atlas_rgba_ = std::move(image.pixels);
    // -yorigin top flips the metrics' vertical axis to y-down (ascender
    // comes out negative); our Glyph model is y-up, so negate.
    font.em_size_ = static_cast<float>(atlas.get("size").as_number(32.0));
    font.px_range_ =
        static_cast<float>(atlas.get("distanceRange").as_number(4.0));
    font.ascender_ =
        -static_cast<float>(metrics.get("ascender").as_number(-0.9));
    font.descender_ =
        -static_cast<float>(metrics.get("descender").as_number(0.2));
    font.line_height_ =
        static_cast<float>(metrics.get("lineHeight").as_number(1.2));

    const float aw = static_cast<float>(font.atlas_width_);
    const float ah = static_cast<float>(font.atlas_height_);
    font.glyphs_.reserve(glyphs.array().size());
    for (const json::Value& gv : glyphs.array()) {
        Glyph g;
        g.codepoint = static_cast<uint32_t>(gv.get("unicode").as_int(0));
        g.advance = static_cast<float>(gv.get("advance").as_number(0.0));
        const json::Value& pb = gv.get("planeBounds");
        const json::Value& ab = gv.get("atlasBounds");
        if (pb.is_object() && ab.is_object()) {
            g.plane_l = static_cast<float>(pb.get("left").as_number(0.0));
            g.plane_r = static_cast<float>(pb.get("right").as_number(0.0));
            // y-down plane bounds -> y-up: negate and swap top/bottom.
            g.plane_t = -static_cast<float>(pb.get("top").as_number(0.0));
            g.plane_b = -static_cast<float>(pb.get("bottom").as_number(0.0));
            // -yorigin top: atlas "top" is the smaller y, v-down like our
            // UV convention.
            g.uv_l = static_cast<float>(ab.get("left").as_number(0.0)) / aw;
            g.uv_r = static_cast<float>(ab.get("right").as_number(0.0)) / aw;
            g.uv_t = static_cast<float>(ab.get("top").as_number(0.0)) / ah;
            g.uv_b =
                static_cast<float>(ab.get("bottom").as_number(0.0)) / ah;
            g.has_geometry = true;
        }
        font.glyphs_.push_back(g);
    }
    if (font.glyphs_.empty()) return std::nullopt;
    std::sort(font.glyphs_.begin(), font.glyphs_.end(),
              [](const Glyph& a, const Glyph& b) {
                  return a.codepoint < b.codepoint;
              });
    return font;
}

const Glyph* Font::find_glyph(uint32_t codepoint) const {
    auto it = std::lower_bound(
        glyphs_.begin(), glyphs_.end(), codepoint,
        [](const Glyph& g, uint32_t cp) { return g.codepoint < cp; });
    if (it != glyphs_.end() && it->codepoint == codepoint) return &*it;
    if (codepoint != '?') return find_glyph('?');
    return glyphs_.empty() ? nullptr : &glyphs_.front();
}

uint32_t utf8_decode(const char* text, size_t length, size_t* cursor) {
    constexpr uint32_t kReplacement = 0xFFFD;
    size_t i = *cursor;
    if (i >= length) return kReplacement;

    const uint8_t b0 = static_cast<uint8_t>(text[i]);
    uint32_t cp = 0;
    size_t extra = 0;
    if (b0 < 0x80) {
        *cursor = i + 1;
        return b0;
    } else if ((b0 & 0xE0) == 0xC0) {
        cp = b0 & 0x1F;
        extra = 1;
    } else if ((b0 & 0xF0) == 0xE0) {
        cp = b0 & 0x0F;
        extra = 2;
    } else if ((b0 & 0xF8) == 0xF0) {
        cp = b0 & 0x07;
        extra = 3;
    } else {
        *cursor = i + 1;
        return kReplacement;
    }
    if (i + extra >= length) {
        *cursor = i + 1;
        return kReplacement;
    }
    for (size_t k = 1; k <= extra; ++k) {
        const uint8_t b = static_cast<uint8_t>(text[i + k]);
        if ((b & 0xC0) != 0x80) {
            *cursor = i + 1;
            return kReplacement;
        }
        cp = (cp << 6) | (b & 0x3F);
    }
    // Reject overlong encodings, surrogates, and out-of-range values.
    static constexpr uint32_t kMinForExtra[4] = {0, 0x80, 0x800, 0x10000};
    if (cp < kMinForExtra[extra] || cp > 0x10FFFF ||
        (cp >= 0xD800 && cp <= 0xDFFF)) {
        *cursor = i + 1;
        return kReplacement;
    }
    *cursor = i + extra + 1;
    return cp;
}

